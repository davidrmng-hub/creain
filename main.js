const nodes = [...document.querySelectorAll('[data-i18n],[data-i18n-html]')];
nodes.forEach(n => { n.dataset.es = n.hasAttribute('data-i18n-html') ? n.innerHTML : n.textContent; });

function setLang(lang){
  nodes.forEach(n => {
    const key = n.dataset.i18n || n.dataset.i18nHtml;
    const val = lang === 'en' ? (EN[key] ?? n.dataset.es) : n.dataset.es;
    if (n.hasAttribute('data-i18n-html')) n.innerHTML = val; else n.textContent = val;
  });
  document.documentElement.lang = lang;
  const [es, en] = document.querySelectorAll('#langToggle span');
  es.classList.toggle('on', lang === 'es'); en.classList.toggle('on', lang === 'en');
  try { localStorage.setItem('creain-lang', lang); } catch(e) {}
}
let lang = 'es';
try { lang = localStorage.getItem('creain-lang') || (navigator.language || 'es').slice(0,2); } catch(e) {}
if (lang !== 'en') lang = 'es';
if (lang === 'en') setLang('en');
document.getElementById('langToggle').addEventListener('click', () => {
  lang = lang === 'es' ? 'en' : 'es'; setLang(lang);
});

